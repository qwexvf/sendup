// Bundles the React dashboard and writes src/dashboard-html.js — a single self-contained
// HTML document the Worker serves inline. Committing the output means `wrangler deploy`
// never needs bun installed.

const out = await Bun.build({
  entrypoints: ['./main.tsx'],
  target: 'browser',
  format: 'iife',
  minify: true,
  define: { 'process.env.NODE_ENV': '"production"' },
})

if (!out.success) {
  for (const log of out.logs) console.error(log)
  process.exit(1)
}

const js = await out.outputs[0].text()
const css = await Bun.file('./node_modules/@cloudflare/kumo/dist/styles/kumo-standalone.css').text()

// </script> inside the bundle would close the tag early
const safe = (s: string) => s.replaceAll('</', '<\\/')

// Dark unless the visitor has explicitly chosen light. Applied before first paint so
// there is no white flash on load.
const modeBoot = `
try {
  var m = localStorage.getItem('sendup:mode')
  document.documentElement.dataset.mode = m === 'light' ? 'light' : 'dark'
} catch (e) { document.documentElement.dataset.mode = 'dark' }
`

// Kumo owns typography and colour. The only thing added here is telling the browser
// which scheme is active so native controls and scrollbars match.
const typography = `
html{ color-scheme: dark }
html[data-mode="light"]{ color-scheme: light }
`

const html = `<!doctype html>
<html lang="en" class="kumo" data-mode="dark" data-theme="kumo">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex,nofollow">
<meta name="color-scheme" content="dark light">
<title>sendup</title>
<script>${modeBoot}</script>
<style>${css}</style>
<style>${typography}</style>
</head>
<body class="bg-kumo text-kumo">
<div id="root"></div>
<script>window.__SENDUP_BASE__=${JSON.stringify('__BASE__')}</script>
<script>${safe(js)}</script>
</body>
</html>`

const escaped = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')

await Bun.write(
  '../src/dashboard-html.js',
  `// GENERATED by dash/build.ts — do not edit. Run \`bun run build\` in dash/.\nexport const DASHBOARD_HTML = \`${escaped}\`\n`
)

const kb = (n: number) => `${(n / 1024).toFixed(1)} KB`
console.log(`js   ${kb(js.length)}\ncss  ${kb(css.length)}\nhtml ${kb(html.length)}`)
